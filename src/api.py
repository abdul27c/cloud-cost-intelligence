
import json
import subprocess
import sys
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "sample-data"

ANALYSIS_REPORT = DATA_DIR / "analysis_report.json"
INVESTIGATION_REPORT = DATA_DIR / "investigation_report.json"

ANALYZER = ROOT / "src" / "analyzer.py"
CORRELATOR = ROOT / "src" / "change_correlator.py"

app = FastAPI(
    title="Cloud Cost Intelligence API",
    description="API for cloud spending analysis and anomaly investigation.",
    version="0.1.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173"],
    allow_credentials=False,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type"],
)


def read_report(path: Path):
    """Read a JSON report generated by the analytics engine."""
    if not path.exists():
        raise HTTPException(
            status_code=503,
            detail=f"Report not found: {path.name}. Run the analysis first.",
        )

    try:
        with path.open(encoding="utf-8") as file:
            return json.load(file)
    except (OSError, json.JSONDecodeError) as error:
        raise HTTPException(
            status_code=500,
            detail=f"Could not read {path.name}: {error}",
        ) from error


def run_script(script_path: Path):
    """Run a known project script and report failures."""
    try:
        result = subprocess.run(
            [sys.executable, str(script_path)],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )
    except subprocess.TimeoutExpired as error:
        raise HTTPException(
            status_code=504,
            detail=f"{script_path.name} exceeded the 60-second limit.",
        ) from error

    if result.returncode != 0:
        raise HTTPException(
            status_code=500,
            detail={
                "message": f"{script_path.name} failed.",
                "error": result.stderr[-3000:],
            },
        )

    return result.stdout


@app.get("/api/health")
def health():
    return {"status": "ok", "service": "Cloud Cost Intelligence API"}


@app.get("/api/overview")
def overview():
    """Return the actual cost-analysis report."""
    return read_report(ANALYSIS_REPORT)


@app.get("/api/investigations")
def investigations():
    """Return the actual change-correlation report."""
    return read_report(INVESTIGATION_REPORT)


@app.post("/api/refresh")
def refresh():
    """Regenerate the cost report and then investigate its anomalies."""
    run_script(ANALYZER)
    run_script(CORRELATOR)

    return {
        "status": "success",
        "message": "Cost analysis and investigations refreshed.",
        "overview": read_report(ANALYSIS_REPORT),
        "investigations": read_report(INVESTIGATION_REPORT),
    }
